package cl.kanopus.excel.writer.iterator;

import cl.kanopus.common.data.Paginator;
import cl.kanopus.common.data.Searcher;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.util.List;

/**
 * Exports all the records returned page by page by {@link #findRecords(Searcher)} to an XLSX workbook.
 */
public abstract class ExcelReaderIterator<T> {

    private static final int PAGE_SIZE = 1000;

    /** Generates the workbook in memory and returns it as an input stream. */
    public <I extends Searcher<?>> InputStream read(I searcher) throws IOException {
        ExposedByteArrayOutputStream out = new ExposedByteArrayOutputStream();
        write(searcher, out);
        return out.toInputStream();
    }

    /** Generates the workbook directly into the given stream (which is not closed). */
    public <I extends Searcher<?>> void write(I searcher, OutputStream out) throws IOException {
        try (RecordsExcel excel = new RecordsExcel()) {
            excel.createHeaders(header());

            int offset = 0;
            searcher.setLimit(PAGE_SIZE);
            searcher.setOffset(0);
            List<T> records = records(findRecords(searcher));
            while (!records.isEmpty()) {
                for (T f : records) {
                    offset++;
                    excel.createRecord(row(f));
                }
                searcher.setOffset(offset);
                records = records(findRecords(searcher));
            }

            excel.autoSize();
            excel.autoFilter();
            excel.write(out);
        }
    }

    private List<T> records(Paginator<T> paginator) {
        return paginator == null || paginator.getRecords() == null ? List.of() : paginator.getRecords();
    }

    /** Avoids copying the generated bytes again when exposing them as an input stream. */
    private static final class ExposedByteArrayOutputStream extends ByteArrayOutputStream {

        InputStream toInputStream() {
            return new ByteArrayInputStream(buf, 0, count);
        }
    }

    protected abstract <I extends Searcher<?>> Paginator<T> findRecords(I searcher);

    protected abstract List<String> header();

    protected abstract List<Object> row(T object);
}
